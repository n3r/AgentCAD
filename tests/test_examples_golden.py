"""PRD-010 slice 1 — the identity harness for the bundled example parts.

Nothing here ships to a user. This module writes down what the three
``construction`` parts (plus ``rocketry/flange`` and
``prototyping/enclosure_lid`` as controls) measure and tessellate to *today*,
before ``toolkit.patterns``/``toolkit.holes`` exist, so slice 7's rewrite of
those scripts cannot quietly change the geometry and slices 3/4 cannot quietly
change what a hole is.

**The criterion this harness encodes.** PRD-010's AC1 asks the rewrite to keep
"the same content-hash mesh-cache entries", which is impossible: the cache key
hashes the *script text* (``service._cache_key``), so any rewrite whatsoever
mints a new key. The design spec restates it, and this is the restated form:

  (a) every metric equal to the golden — ``volume_mm3``, ``area_mm2``,
      ``mass_g``, ``bbox`` and ``center_of_mass`` at ``rel=1e-9``, and
      ``n_faces``/``n_edges``/``n_solids`` exactly; **and**
  (b) a **byte-identical ``.acm`` payload** under the new key.

(b) is the load-bearing half and it is not implied by (a): measured on
``gusset_plate`` through the worker at its shipped params, cutting the same
holes with ``part - Compound(cylinders)`` instead of
``Locations(...)``/``Hole(...)`` gives the same face and edge counts and a
volume that differs in the last bits (320571.0948520879 vs
320571.09485208784 — a relative 2e-16, well inside ``rel=1e-9``) and a
**different** mesh (``56b50449…`` vs ``a00ec644…``). Only the route that
re-enters a ``BuildPart`` and ``add()``s the caller's part reproduces the
shipped bytes — measured byte-identical on all three parts below, through the
worker (changelog 0147, spike S1). A golden that checked metrics alone would
pass the wrong implementation.

**The goldens are literals below**, generated by running this module once
against the committed examples — not a JSON fixture nobody reads. If a golden
moves, that is a finding to explain in the changelog, never a number to
re-baseline.

``measure_part`` and ``script_acm_sha256`` are the reusable half: slices 3, 4
and 7 assert byte-identity through them rather than growing a second harness.
"""

